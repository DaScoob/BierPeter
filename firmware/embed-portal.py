"""Generate a flash-resident header from the reviewable portal source."""
from pathlib import Path
root=Path(__file__).resolve().parent
html=(root/'portal.html').read_text()
if ')BierPeterHTML"' in html:raise ValueError('Raw-string delimiter collision')
header='// SPDX-License-Identifier: AGPL-3.0-only\n// Generated by firmware/embed-portal.py. Edit firmware/portal.html.\n#pragma once\nstatic const char PortalPage[] PROGMEM=R"BierPeterHTML('+html+')BierPeterHTML";\n'
(root/'include/Portal.h').write_text(header)
